from __future__ import annotations

import json
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

from evals.fixtures import make_workspace
from evals.models import CaseSpec, load_cases
from evals.runner import Observation, check_result
from tests.test_eval_runner import SOURCE


class CompleteResearchCaseTests(unittest.TestCase):
    def case(self) -> CaseSpec:
        return next(
            case
            for case in load_cases(SOURCE / "evals/cases")
            if case.id == "complete-research-investigation"
        )

    def test_local_probe_packet_reproduces_the_decision_relevant_outcomes(self) -> None:
        case = self.case()
        with tempfile.TemporaryDirectory(prefix="main-paths-research-") as directory:
            root = Path(directory)
            for name, content in case.files.items():
                target = root / name
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(content)
            completed = subprocess.run(
                [
                    sys.executable,
                    "probes/run_storage.py",
                    "--output",
                    str(root / "runs"),
                ],
                cwd=root,
                capture_output=True,
                text=True,
                check=True,
                timeout=20,
            )
            summary = json.loads(completed.stdout)
            self.assertEqual(
                summary, json.loads((root / "runs/summary.json").read_text())
            )
            results = summary["adapters"]
            self.assertEqual(set(results), {"snapshot", "sqlite", "sqlite-guarded"})
            for backend, scenarios in results.items():
                with self.subTest(backend=backend):
                    reopened = scenarios["reopen"]["reopened"]
                    self.assertEqual(reopened["a"]["body"], "saved-offline")
                    self.assertEqual(reopened["a"]["id"], "a")
                    self.assertEqual(reopened["b"]["id"], "b")
                    interrupted = scenarios["interrupted-pair"]
                    self.assertEqual(interrupted["worker_exit"], 23)
                    self.assertEqual(
                        [interrupted["reopened"][key]["body"] for key in ("a", "b")],
                        ["old-a", "old-b"],
                    )
                    different = scenarios["different-note-windows"]
                    self.assertEqual(different["second_save"], "accepted")
                    self.assertEqual(different["reopened"]["b"]["body"], "second-edit")
                    self.assertEqual(
                        different["reopened"]["a"]["body"],
                        "old-a" if backend == "snapshot" else "first-edit",
                    )
                    same = scenarios["same-note-windows"]
                    self.assertEqual(
                        same["second_save"],
                        "conflict" if backend == "sqlite-guarded" else "accepted",
                    )
                    self.assertEqual(
                        same["reopened"]["a"]["body"],
                        "first-edit" if backend == "sqlite-guarded" else "second-edit",
                    )

    def test_preservation_checks_allow_reports_and_cache_but_reject_source_changes(
        self,
    ) -> None:
        case = self.case()
        checks = case.steps[-1].checks
        with make_workspace(SOURCE, case) as workspace:
            report = workspace.file("docs/research/offline-storage.md")
            cache = workspace.file("src/__pycache__/app.pyc")
            cache.parent.mkdir(parents=True)
            cache.write_bytes(b"generated bytecode")
            # Report meaning is assessed privately, not by matching its prose here.
            for content in (
                "A guarded database is feasible; "
                "the portability choice remains open.\n",
                "| Store | Required work |\n| --- | --- |\n"
                "| JSON | Coordinate stale saves |\n",
            ):
                report.write_text(content)
                for check in checks:
                    self.assertTrue(
                        check_result(check, Observation(), workspace, "main", [])[0]
                    )
            for name in ("src/app.py", "sources/storage/sqlite-0.3.md"):
                with self.subTest(name=name):
                    target = workspace.file(name)
                    target.write_text("Changed input.\n")
                    self.assertFalse(
                        check_result(checks[0], Observation(), workspace, "main", [])[0]
                    )
                    target.write_text(case.files[name])
            added = workspace.file("src/storage.py")
            added.write_text("def save(): pass\n")
            self.assertFalse(
                check_result(checks[0], Observation(), workspace, "main", [])[0]
            )

    def test_publication_check_allows_reads_and_rejects_publication_attempts(
        self,
    ) -> None:
        case = self.case()
        check = case.steps[-1].checks[1]
        with make_workspace(SOURCE, case) as workspace:
            calls = workspace.home / "work-system/service-calls.jsonl"
            for call, expected in (
                (["issue", "view", "11"], True),
                (["pr", "create", "--title", "Offline storage"], False),
                (["issue", "create", "--title", "Offline storage"], False),
            ):
                with self.subTest(call=call):
                    calls.write_text(json.dumps(call) + "\n")
                    self.assertEqual(
                        check_result(check, Observation(), workspace, "main", [])[0],
                        expected,
                    )


if __name__ == "__main__":
    unittest.main()
